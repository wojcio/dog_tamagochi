import sys

def create_tile(pixels):
    tile = bytearray(16)
    for y in range(8):
        row = str(pixels[y]) if y < len(pixels) else "00000000"
        if len(row) < 8:
            row = row.ljust(8, '0')
        p0 = 0
        p1 = 0
        for x in range(8):
            c = int(row[x]) if row[x] in '0123' else 0
            if c & 1: p0 |= (1 << (7 - x))
            if c & 2: p1 |= (1 << (7 - x))
        tile[y] = p0
        tile[y + 8] = p1
    return tile

