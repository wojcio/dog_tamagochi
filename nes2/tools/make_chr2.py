import sys

def create_tile(pixels):
    tile = bytearray(16)
    for y in range(8):
        row = pixels[y] if y < len(pixels) else "00000000"
        if len(row) < 8:
            row = row.ljust(8, '0')
        plane0 = 0
        plane1 = 0
        for x in range(8):
            color = int(row[x]) if row[x] in '0123' else 0
            if color & 1:
                plane0 |= (1 << (7 - x))
            if color & 2:
                plane1 |= (1 << (7 - x))
        tile[y] = plane0
        tile[y + 8] = plane1
    return tile

