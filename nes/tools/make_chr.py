def hex_tile_to_2bpp(plane0, plane1=None):
    if plane1 is None:
        plane1 = [0] * 8
    return bytes(plane0 + plane1)

def str_to_tile(lines, col1_char='#', col2_char='*', col3_char='@'):
    plane0 = []
    plane1 = []
    for line in lines:
        line = line.ljust(8, ' ')[:8]
        b0 = 0
        b1 = 0
        for i, ch in enumerate(line):
            shift = 7 - i
            if ch == col1_char:
                b0 |= (1 << shift)
            elif ch == col2_char:
                b1 |= (1 << shift)
            elif ch == col3_char:
                b0 |= (1 << shift)
                b1 |= (1 << shift)
        plane0.append(b0)
        plane1.append(b1)
    return hex_tile_to_2bpp(plane0, plane1)

